import { createApp, nextTick } from "vue";
import { createPinia } from "pinia";
import { createMemoryHistory, createRouter } from "vue-router";
import NearbyTransfer from "../../src/views/NearbyTransfer.vue";
import { nearbyState, renameNearbyDevice, resetNearby } from "../../src/services/nearbySession";
import { useUIStore } from "../../src/stores/ui";
import { useKeyStore } from "../../src/stores/keys";
import { deviceStorage } from "../../src/services/deviceStorage";
import { NEARBY_UNNAMED_PEER } from '../../src/services/nearbyTransfer';
import qrcode from 'qrcode-generator';

/** Exercise real composer bindings, staged attachments and batch saving. */
export async function validateTransferAssistant() {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: "/nearby", component: NearbyTransfer }] });
  await router.push("/nearby");
  const shareDescriptor = Object.getOwnPropertyDescriptor(navigator, "share");
  const canShareDescriptor = Object.getOwnPropertyDescriptor(navigator, "canShare");
  const cameraDescriptor = Object.getOwnPropertyDescriptor(navigator.mediaDevices, 'getUserMedia');
  Object.defineProperty(navigator.mediaDevices, 'getUserMedia', { configurable: true, value: async () => { throw new DOMException('Denied', 'NotAllowedError'); } });
  const shared: File[][] = [];
  let shareError: Error | undefined;
  Object.defineProperty(navigator, "canShare", { configurable: true, value: () => true });
  Object.defineProperty(navigator, "share", { configurable: true, value: async ({ files }: { files: File[] }) => { if (shareError) throw shareError; shared.push(files); } });
  const pinia = createPinia();
  const app = createApp(NearbyTransfer).use(pinia).use(router);
  const ui = useUIStore(pinia);
  const settle = async () => { await new Promise(resolve => setTimeout(resolve, 0)); await nextTick(); };
  const click = (selector: string) => document.querySelector<HTMLButtonElement>(selector)!.click();
  try {
    const png = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a7X0AAAAASUVORK5CYII='), c => c.charCodeAt(0));
    const files = [new File([png], "照片.png", { type: "image/png" }), new File(["pdf"], "文档.pdf", { type: "application/pdf" })];
    nearbyState.pairKey = { roomId: "preview", password: "preview" };
    nearbyState.pairPeers = { peer: "Linux 电脑" };
    nearbyState.pairTextPeers = { peer: true };
    nearbyState.transfers.push({
      id: "fixture", kind: "pair", peerId: "peer", direction: "in", peerName: "Linux 电脑",
      localDeviceName: "iPhone", createdAt: Date.now(),
      files: files.map(file => ({ name: file.name, size: file.size, type: file.type })),
      progress: [1, 1], received: files, state: "done",
    });
    app.mount("#app");
    await nextTick();
    const waitFor = async (predicate: () => boolean) => {
      for (let attempt = 0; attempt < 250; attempt++) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 20)); }
      throw new Error('timed out waiting for scanner');
    };
    nearbyState.pairKey = null;
    nearbyState.pairPeers = {};
    click('[aria-label="设备与连接"]');
    await nextTick();
    click('.scan-device');
    await nextTick();
    if (!document.querySelector('.scanner-overlay') || document.querySelector('.connection-sheet')) throw new Error('device panel must close before opening scanner');
    const frame = document.querySelector('.camera-frame')!.getBoundingClientRect();
    if (!document.querySelector('.scanner-overlay')!.contains(document.elementFromPoint(frame.x + frame.width / 2, frame.y + frame.height / 2))) throw new Error('scanner must not be covered by another panel');
    await waitFor(() => !!document.querySelector('.scanner-sheet .error'));
    if (document.querySelector('.connection-sheet')) throw new Error('camera denial must leave the scanner and photo fallback visible');
    // Decode a real QR image to exercise scanner completion and panel restoration.
    const qr = qrcode(0, 'M'); qr.addData('not-a-hainei-pairing-link'); qr.make();
    const image = new Image(); image.src = qr.createDataURL(5, 4); await image.decode();
    const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
    canvas.getContext('2d')!.drawImage(image, 0, 0);
    const blob = await new Promise<Blob>(resolve => canvas.toBlob(value => resolve(value!), 'image/png'));
    const qrInput = document.querySelector<HTMLInputElement>('.scanner-sheet input')!;
    const qrSelection = new DataTransfer(); qrSelection.items.add(new File([blob], 'qr.png', { type: 'image/png' }));
    qrInput.files = qrSelection.files; qrInput.dispatchEvent(new Event('change', { bubbles: true }));
    await waitFor(() => !document.querySelector('.scanner-overlay'));
    if (!document.querySelector('.connection-sheet')) throw new Error('decoded QR must close the scanner and restore the connection panel');
    click('.scan-device'); await nextTick();
    click('.scanner-header button'); await nextTick();
    if (document.querySelector('.scanner-overlay') || !document.querySelector('.connection-sheet')) throw new Error('canceling scan must restore the device panel');
    click('[aria-label="关闭设备与连接"]');
    nearbyState.pairKey = { roomId: 'preview', password: 'preview' };
    nearbyState.pairPeers = { peer: 'Linux 电脑' };
    await nextTick();
    if (!document.querySelector('.file-thumbnail img')) throw new Error('received images must show a thumbnail');
    click('.file-thumbnail'); await nextTick();
    if (!document.querySelector('.image-preview img')) throw new Error('thumbnail must open full preview');
    if (!document.querySelector('.image-preview a[download]')) throw new Error('image preview must retain individual saving');
    click('[aria-label="关闭图片预览"]'); await nextTick();
    if (document.querySelector(".assistant-body .device-card, .assistant-body .diagnostics, .connection-status, .choose-files")) throw new Error("chat must not contain duplicate connection or file-picker controls");
    const save = document.querySelector<HTMLButtonElement>(".batch-save");
    const send = document.querySelector<HTMLButtonElement>('[aria-label="发送"]')!;
    const textarea = document.querySelector<HTMLTextAreaElement>('[aria-label="输入消息"]')!;
    if (!save || !textarea || !send.disabled) throw new Error("empty composer must render with sending disabled");
    if (!document.querySelector('.transfer-head')?.textContent?.includes('Linux 电脑 → iPhone') || !document.querySelector('.transfer-time')?.textContent?.includes('接收于')) throw new Error('records must identify both devices and reception time');
    if (save.textContent !== '保存全部' || document.querySelector('.file-cards a[download]')) throw new Error('completed batches must have one save action below the cards');
    const fixture = nearbyState.transfers[0];
    const originalMeta = fixture.files;
    fixture.files = fixture.files.slice(0, 1); fixture.received = [files[0]];
    await nextTick();
    if (String(save.textContent) !== '保存' || document.querySelector('.file-cards a[download]')) throw new Error('single files must have one concise save action');
    fixture.files = originalMeta; fixture.received = files;
    await nextTick();
    shareError = new DOMException('Canceled', 'AbortError');
    save.click();
    await settle();
    if (nearbyState.transfers[0].saveState || document.querySelector('.confirm-saved')) throw new Error('canceling the share sheet must not mark a file saved');
    shareError = new Error('Share failed');
    save.click();
    await settle();
    if (nearbyState.transfers[0].saveState) throw new Error('failed share must not mark a file saved');
    shareError = undefined;
    save.click();
    await settle();
    if (shared.length !== 1 || shared[0].length !== 2) throw new Error("batch save must share original files together");
    if (nearbyState.transfers[0].saveState !== 'system' || !document.querySelector('.save-hint')?.textContent?.includes('已交给系统')) throw new Error('share completion must report handoff rather than disk save');
    click('.confirm-saved');
    await nextTick();
    if (String(nearbyState.transfers[0].saveState) !== 'saved' || !document.querySelector('.save-hint')?.textContent?.includes('✓ 已保存') || document.querySelector('.confirm-saved')) throw new Error('save confirmation must remain visible as saved');
    const input = document.querySelector<HTMLInputElement>(".hidden-input")!;
    let pickerCalls = 0;
    input.click = () => { pickerCalls++; };
    const pickBatch = () => {
      const selection = new DataTransfer();
      files.forEach(file => selection.items.add(file));
      input.files = selection.files;
      input.dispatchEvent(new Event("change", { bubbles: true }));
    };
    const typeText = (text: string) => { textarea.value = text; textarea.dispatchEvent(new Event("input", { bubbles: true })); };
    const selectedChip = () => document.querySelector('.target-chip.selected')?.textContent || '';
    const chip = (name: string) => [...document.querySelectorAll<HTMLButtonElement>('button.target-chip')].find(item => item.textContent?.includes(name))!;
    if (!selectedChip().includes('Linux 电脑')) throw new Error('a single device must be selected automatically');
    nearbyState.pairPeers = { peer: NEARBY_UNNAMED_PEER };
    typeText('pending connection'); await nextTick();
    if (!send.disabled || !chip('连接中').disabled) throw new Error('unidentified connections must not be presented as ready');
    nearbyState.pairPeers = { peer: 'Linux 电脑' };
    typeText(''); await nextTick();
    click(".attachment-button");
    pickBatch();
    await nextTick();
    if (pickerCalls !== 1 || send.disabled) throw new Error("attachments must be staged until send is clicked");
    const staged = () => document.querySelectorAll('.staged-file').length;
    if (staged() !== 2 || !document.querySelector('.staged-file img')) throw new Error('staged files must be listed with image thumbnails');
    click(".attachment-button"); pickBatch(); await nextTick();
    if (staged() !== 2) throw new Error('picking the same files again must not duplicate them');
    const extra = new File(['notes'], '笔记.txt', { type: 'text/plain' });
    const addOne = new DataTransfer(); addOne.items.add(extra);
    click(".attachment-button"); input.files = addOne.files; input.dispatchEvent(new Event("change", { bubbles: true })); await nextTick();
    if (staged() !== 3) throw new Error('picking more files must append to the staged batch');
    click('[aria-label="移除 笔记.txt"]'); await nextTick();
    if (staged() !== 2 || document.body.textContent?.includes('笔记.txt')) throw new Error('one staged file must be removable on its own');
    const pasted = new DataTransfer(); pasted.items.add(new File([png], 'image.png', { type: 'image/png' }));
    const paste = new ClipboardEvent('paste', { clipboardData: pasted, bubbles: true, cancelable: true });
    textarea.dispatchEvent(paste); await nextTick();
    if (staged() !== 3 || !paste.defaultPrevented || textarea.value) throw new Error('pasting an image must stage it instead of inserting text');
    const plain = new DataTransfer(); plain.setData('text/plain', 'just text');
    const textPaste = new ClipboardEvent('paste', { clipboardData: plain, bubbles: true, cancelable: true });
    textarea.dispatchEvent(textPaste);
    if (textPaste.defaultPrevented || staged() !== 3) throw new Error('plain text paste must keep its default behaviour');
    const dropped = new DataTransfer(); dropped.items.add(new File(['zip'], '资料.zip', { type: 'application/zip' }));
    const page = document.querySelector('.nearby-page')!;
    page.dispatchEvent(new DragEvent('dragenter', { dataTransfer: dropped, bubbles: true, cancelable: true })); await nextTick();
    if (!document.querySelector('.drop-overlay')) throw new Error('dragging files over the page must show the drop target');
    const drop = new DragEvent('drop', { dataTransfer: dropped, bubbles: true, cancelable: true });
    page.dispatchEvent(drop); await nextTick();
    if (staged() !== 4 || !drop.defaultPrevented || document.querySelector('.drop-overlay')) throw new Error('dropping files must stage them and hide the drop target');
    click('[aria-label="移除 资料.zip"]'); click('[aria-label="移除 image.png"]'); await nextTick();
    if (staged() !== 2) throw new Error('fixture batch must be restored before sending');
    const beforeFiles = ui.toasts.length;
    send.click();
    await settle();
    // No transport room exists in this isolated fixture. A toast proves that
    // the real send path was invoked, without starting a network connection.
    if (ui.toasts.length !== beforeFiles + 1) throw new Error("send must submit directly to the selected device");
    click(".selected-batch button");
    await nextTick();
    typeText("第一行\n第二行");
    await nextTick();
    textarea.focus();
    await nextTick();
    if (getComputedStyle(textarea).fontSize !== "16px" || textarea.scrollWidth > textarea.clientWidth + 1) throw new Error("composer text must retain mobile sizing");
    const beforeText = ui.toasts.length;
    send.click();
    await settle();
    if (ui.toasts.length !== beforeText + 1 || textarea.value !== "第一行\n第二行") throw new Error("failed text submission must restore the draft");
    nearbyState.pairTextPeers = {};
    await nextTick();
    if (!send.disabled || !document.querySelector('.recipient-hint')) throw new Error('unsupported text must disable sending before submission');
    nearbyState.pairTextPeers = { peer: true };
    await nextTick();
    const beforeSelection = ui.toasts.length;
    chip('Linux 电脑').click();
    await nextTick();
    if (ui.toasts.length !== beforeSelection || textarea.value !== '第一行\n第二行' || send.disabled) throw new Error('selecting a device must preserve the draft without sending');
    nearbyState.pairPeers = { peer: 'Linux 电脑', second: 'iPad' };
    nearbyState.pairTextPeers = { peer: true, second: true };
    await nextTick();
    if (!selectedChip().includes('Linux 电脑') || !chip('iPad')) throw new Error('new peers must appear without changing the recipient');
    nearbyState.pairPeers = { second: 'iPad' };
    await nextTick();
    if (!send.disabled || selectedChip() || !document.querySelector('.target-chip.lost')) throw new Error('disconnect must not silently redirect to another device');
    chip('iPad').click();
    await nextTick();
    if (!selectedChip().includes('iPad') || send.disabled || document.querySelector('.target-chip.lost')) throw new Error('recipient switching must occur before send');
    await nextTick();
    click('[aria-label="设备与连接"]');
    await nextTick();
    click(".peer-send");
    await nextTick();
    if (!selectedChip() || document.querySelector(".connection-sheet")) throw new Error("device selection must stage a recipient");
    const beforeSelected = ui.toasts.length;
    send.click();
    await settle();
    if (ui.toasts.length !== beforeSelected + 1) throw new Error("explicit recipient must not be selected twice");
    click(".attachment-button");
    pickBatch();
    await nextTick();
    if (!document.querySelector(".selected-batch") || !textarea.value) throw new Error("adding files must not submit text automatically");
    click(".attachment-button");
    useKeyStore(pinia).pkHex = "fixture-account";
    await nextTick();
    pickBatch();
    await nextTick();
    if (textarea.value || document.querySelector(".selected-batch") || selectedChip().includes('iPad')) throw new Error("account switch must clear draft, attachments and recipient");
    nearbyState.pairPeers = {};
    await nextTick();
    typeText('offline draft');
    await nextTick();
    if (!send.disabled || !document.querySelector('.connect-device')?.textContent?.includes('连接设备')) throw new Error('no devices must show connection action and disable sending');
    click('.connect-device');
    await nextTick();
    if (!document.querySelector('.connection-sheet')) throw new Error('connection action must open device connections');
    click('[aria-label="关闭设备与连接"]');
    deviceStorage.removeItem('hainei_nearby_last_device');
    nearbyState.ownPeers = { o1: 'MacBook', o2: 'iPad' };
    nearbyState.ownDevices = { o1: '1'.repeat(16), o2: '2'.repeat(16) };
    nearbyState.ownTextPeers = { o1: true, o2: true };
    await nextTick();
    if (selectedChip()) throw new Error('two devices must not be chosen automatically');
    chip('MacBook').click(); await nextTick();
    if (deviceStorage.getItem('hainei_nearby_last_device') !== '1'.repeat(16)) throw new Error('the chosen own device must be remembered');
    nearbyState.ownPeers = { o2: 'iPad', o3: 'MacBook' };
    nearbyState.ownDevices = { o2: '2'.repeat(16), o3: '1'.repeat(16) };
    nearbyState.ownTextPeers = { o2: true, o3: true };
    await nextTick();
    if (!selectedChip().includes('MacBook') || document.querySelector('.target-chip.lost')) throw new Error('a reloaded device must stay selected under its new connection');
    nearbyState.ownPeers = { o2: 'iPad', o4: 'MacBook' };
    nearbyState.ownDevices = { o2: '2'.repeat(16), o4: '3'.repeat(16) };
    await nextTick();
    if (selectedChip() || !document.querySelector('.target-chip.lost')) throw new Error('another device with the same name must not inherit the selection');
    click('[aria-label="连接更多设备"]'); await nextTick();
    click('.rename-device'); await nextTick();
    const nameInput = document.querySelector<HTMLInputElement>('[aria-label="本机名称"]')!;
    if (document.activeElement !== nameInput) throw new Error('rename must focus the name field');
    nameInput.value = '测试 iPhone'; nameInput.dispatchEvent(new Event('input', { bubbles: true }));
    nameInput.form!.requestSubmit(); await nextTick();
    if (nearbyState.deviceName !== '测试 iPhone' || !document.querySelector('.device-name-row')?.textContent?.includes('测试 iPhone')) throw new Error('renaming must update this device name');
    click('[aria-label="关闭设备与连接"]'); await nextTick();
    nearbyState.ownPeers = {}; nearbyState.ownDevices = {}; nearbyState.ownTextPeers = {};
    await nextTick();
    nearbyState.transfers.unshift({ id: "restored", kind: "own", peerId: "", direction: "in", peerName: "Mac", restored: true, stored: [true], createdAt: Date.now(),
      files: [{ name: "旧文件.pdf", size: 3, type: "application/pdf" }], progress: [1], received: [undefined], state: "done" });
    nearbyState.transfers.unshift({ id: "restored-out", kind: "own", peerId: "", direction: "out", peerName: "Mac", restored: true, createdAt: Date.now(),
      files: [{ name: "发出.pdf", size: 3, type: "application/pdf" }], progress: [0], received: [undefined], state: "failed" });
    await nextTick();
    const restoredRow = [...document.querySelectorAll('.transfer-row')].find(row => row.textContent?.includes('旧文件.pdf'))!;
    if (!restoredRow.querySelector('.load-history') || restoredRow.querySelector('.batch-save')) throw new Error('restored files must be loaded before saving');
    if (!restoredRow.querySelector('.save-hint')?.textContent?.includes('已加密保存在本机')) throw new Error('stored files must say they are kept encrypted on this device');
    const restoredOut = [...document.querySelectorAll('.transfer-row')].find(row => row.textContent?.includes('发出.pdf'))!;
    if (restoredOut.querySelector('.retry-transfer')) throw new Error('restored sends cannot be retried without the original files');
    nearbyState.transfers.splice(0, 2);
    await nextTick();
    nearbyState.transfers.unshift({ id: "text", kind: "pair", peerId: "peer", direction: "in", peerName: "Linux 电脑", text: "收到的文字\n换行", files: [], progress: [], received: [], state: "done" });
    await nextTick();
    const textBubble = document.querySelector(".transfer-row:last-child")!;
    if (!textBubble.textContent?.includes("收到的文字") || textBubble.querySelector(".batch-save, .batch-files")) throw new Error("text-only records must render as text without file actions");
    click(".transfer-row:last-child .clear-transfer");
    click(".clear-transfer");
    await nextTick();
    if (nearbyState.transfers.length) throw new Error("clear must release local records");
  } finally {
    renameNearbyDevice('');
    deviceStorage.removeItem('hainei_nearby_last_device');
    app.unmount();
    await resetNearby();
    for (const toast of [...ui.toasts]) ui.removeToast(toast.id);
    for (const [name, descriptor] of [["share", shareDescriptor], ["canShare", canShareDescriptor]] as const) {
      if (descriptor) Object.defineProperty(navigator, name, descriptor);
      else delete (navigator as unknown as Record<string, unknown>)[name];
    }
    if (cameraDescriptor) Object.defineProperty(navigator.mediaDevices, 'getUserMedia', cameraDescriptor);
    else delete (navigator.mediaDevices as unknown as Record<string, unknown>).getUserMedia;
  }
}
