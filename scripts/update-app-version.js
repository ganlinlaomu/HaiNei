#!/usr/bin/env node

/**
 * Update App Version in dexie.ts
 * 
 * Keeps APP_VERSION in sync with package.json
 */

const fs = require('fs');
const path = require('path');

const DEXIE_PATH = path.join(__dirname, '..', 'src', 'db', 'dexie.ts');
const RELEASE_INFO_PATH = path.join(__dirname, '..', 'src', 'appRelease.ts');
const PACKAGE_PATH = path.join(__dirname, '..', 'package.json');

// Read package.json to get version
const packageJson = JSON.parse(fs.readFileSync(PACKAGE_PATH, 'utf8'));
const version = packageJson.version;
const releaseSummary = String(packageJson.releaseSummary || '').trim();

if (!releaseSummary) {
  throw new Error('package.json releaseSummary is required for every app version');
}

// Read dexie.ts file
let dexieContent = fs.readFileSync(DEXIE_PATH, 'utf8');

// Update APP_VERSION
dexieContent = dexieContent.replace(
  /export const APP_VERSION = ["'][^"']+["']/,
  `export const APP_VERSION = "${version}"`
);

// Write back to file
fs.writeFileSync(DEXIE_PATH, dexieContent, 'utf8');

const releaseInfo = `// Generated by scripts/update-app-version.js. Keep package.json as the source of truth.
export const APP_UPDATE_SUMMARY = ${JSON.stringify(releaseSummary)};
`;
fs.writeFileSync(RELEASE_INFO_PATH, releaseInfo, 'utf8');

console.log(`✅ APP_VERSION updated to: ${version}`);
console.log(`✅ APP_UPDATE_SUMMARY updated to: ${releaseSummary}`);
